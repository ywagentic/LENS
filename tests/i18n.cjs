const assert=require('node:assert/strict'),fs=require('node:fs'),React=require('react');
const {renderToStaticMarkup}=require('react-dom/server');
const {App,lensText,lensSetLocale,lensLocalePath,lensStripLocale,lensSearchText,normalizeProjects}=require('../.build/server.cjs');
const locales={en:'en',zh:'zh-Hans',es:'es',pt:'pt-BR'};
const html=fs.readFileSync('dist/about/index.html','utf8');
const projects=JSON.parse(html.match(/id="catalogue-data" type="application\/json">(.*?)<\/script>/s)[1]);
const dictionaries=Object.fromEntries(['zh','es','pt'].map(code=>[code,JSON.parse(fs.readFileSync(`config/locales/${code}.json`,'utf8'))]));
const keys=Object.keys(dictionaries.zh).sort();
for(const [code,dict] of Object.entries(dictionaries)){
 assert.deepEqual(Object.keys(dict).sort(),keys,`${code} dictionary coverage differs`);
 assert(Object.values(dict).every(value=>typeof value==='string'&&value.trim()),`${code} has empty translation`);
 assert(dict['Translations are generated by Codex. Accuracy is not guaranteed.'].includes('Codex'));
 lensSetLocale(code);
 assert.equal(lensLocalePath('/projects/tongva-park/?view=gaEUL4jyxEA#view'),`/${code}/projects/tongva-park/?view=gaEUL4jyxEA#view`);
 assert.equal(lensLocalePath('/es/browse/'),`/${code}/browse/`);
 assert.equal(lensLocalePath('/assets/projects/test.jpg'),'/assets/projects/test.jpg');
 assert.equal(lensLocalePath('https://youtube.com/watch?v=abcdefghijk'),'https://youtube.com/watch?v=abcdefghijk');
 assert.equal(lensText('37 Views'),`37 ${dict['Views']}`);
 assert.equal(lensStripLocale(`/${code}/about/`),'/about/');
 assert(lensSearchText(['Seated view']).includes(dict['Seated view'].toLocaleLowerCase()));
 const page=fs.readFileSync(`dist/${code}/about/index.html`,'utf8');
 assert(page.includes(`<html lang="${locales[code]}">`));
 assert(page.includes(dict['About LENS']));
 assert(page.includes('https://doi.org/10.5281/zenodo.23269677'));
 assert(page.includes('Wang, Y. (2026).'));
 assert(page.includes(`href="/${code}/browse/"`));
 for(const [other,tag] of Object.entries(locales))assert(page.includes(`hreflang="${tag}" href="https://lens-vr.com/${other==='en'?'':other+'/'}about/"`));
 const rendered=renderToStaticMarkup(React.createElement(App,{initialProjects:projects,initialPath:`/${code}/projects/tongva-park/`,freezeCatalogue:true}));
 assert(rendered.includes('https://www.youtube.com/watch?v=gaEUL4jyxEA'));
 assert(!rendered.includes('Page not found'));
 const atlas=renderToStaticMarkup(React.createElement(App,{initialProjects:projects,initialPath:`/${code}/atlas/`,freezeCatalogue:true}));
 assert(atlas.includes('value="Urban Park"'));
 assert(atlas.includes(dict['Urban Park']));
}
lensSetLocale('en');assert.equal(lensText('Browse'),'Browse');
const english=renderToStaticMarkup(React.createElement(App,{initialProjects:projects,initialPath:'/about/',freezeCatalogue:true}));assert(english.includes('About LENS'));
assert.equal(lensLocalePath('/zh/about/','en'),'/about/');
console.log('PASS: four locales, per-render isolation, native selectors/disclosure, immutable filter values, localized search, preserved media/citations, locale routes and hreflang.');
